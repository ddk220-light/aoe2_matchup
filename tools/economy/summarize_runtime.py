#!/usr/bin/env python3
"""Regenerate the civilization rate table from the compiled runtime database.

    python tools/economy/summarize_runtime.py            # writes data/army_economics/civilization-rates.csv
                                                         # and the table block in docs/army-economics/README.md
    python tools/economy/summarize_runtime.py --check    # exit 1 if either is stale

Rates are what the labor model uses: credited output per villager-minute of
each activity (secondary outputs such as Poles gold or Shu food in brackets),
and recurring farm/pasture wood per credited food. No hand-maintained tables.
"""
import argparse
import csv
import io
import json
from pathlib import Path
import sqlite3
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from aoe2x.economy.paths import DATA_DIR, RUNTIME_DB  # noqa: E402

RESOURCES = ("food", "wood", "gold", "stone")
CSV_PATH = DATA_DIR / "civilization-rates.csv"
README = ROOT / "docs/army-economics/README.md"
BEGIN, END = "<!-- rate-table:begin (generated by tools/economy/summarize_runtime.py) -->", "<!-- rate-table:end -->"


def rows(db_path):
    with sqlite3.connect(Path(db_path).resolve().as_uri() + "?mode=ro", uri=True) as db:
        civs = [json.loads(p) for (p,) in db.execute("SELECT payload FROM civilizations ORDER BY civ")]
    out = []
    for e in civs:
        acts = {a["id"]: a for a in e["activities"]}
        row = {"civilization": e["civ"]}
        extras, mechanics = [], set()
        for r in RESOURCES:
            a = acts[r]
            row[f"{r}_per_villager_minute"] = round(a["outputs"][r] * 60, 4)
            for k, v in a["outputs"].items():
                if k != r and v > 1e-12:
                    extras.append(f"{r}->{k} {v * 60:.2f}")
            mechanics.update(m["kind"] for m in a.get("appliedMechanics", []))
        food = acts["food"]["outputs"]
        row["recurring_wood_per_food"] = round(-food["wood"] / food["food"], 4)
        row["secondary_outputs_per_villager_minute"] = "; ".join(extras)
        row["mechanics"] = "; ".join(sorted(mechanics))
        row["status"] = ",".join(sorted({a["status"] for a in e["activities"]}))
        out.append(row)
    return out


def to_csv(table):
    buffer = io.StringIO()
    writer = csv.DictWriter(buffer, fieldnames=list(table[0]), lineterminator="\n")
    writer.writeheader()
    writer.writerows(table)
    return buffer.getvalue()


def to_markdown(table):
    lines = ["| Civilization | Food | Wood | Gold | Stone | Farm wood per food | Secondary output | Modeled mechanics |",
             "|---|---:|---:|---:|---:|---:|---|---|"]
    for r in table:
        lines.append(f"| {r['civilization']} | {r['food_per_villager_minute']:.2f} | {r['wood_per_villager_minute']:.2f} | "
                     f"{r['gold_per_villager_minute']:.2f} | {r['stone_per_villager_minute']:.2f} | "
                     f"{r['recurring_wood_per_food']:.4f} | {r['secondary_outputs_per_villager_minute']} | "
                     f"{r['mechanics'].replace('_', ' ')} |")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--db", type=Path, default=RUNTIME_DB)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    table = rows(args.db)
    csv_text, md = to_csv(table), to_markdown(table)
    readme = README.read_text() if README.exists() else ""
    if BEGIN in readme:
        head, rest = readme.split(BEGIN, 1)
        new_readme = head + BEGIN + "\n" + md + "\n" + END + rest.split(END, 1)[1]
    else:
        new_readme = readme
    if args.check:
        stale = [p for p, new in ((CSV_PATH, csv_text), (README, new_readme)) if not p.exists() or p.read_text() != new]
        if stale:
            raise SystemExit(f"Stale generated tables: {', '.join(map(str, stale))}; run {Path(__file__).name}")
        print("Rate tables are current.")
        return
    CSV_PATH.write_text(csv_text)
    if new_readme != readme:
        README.write_text(new_readme)
    print(f"Wrote {CSV_PATH.relative_to(ROOT)} ({len(table)} civilizations)" + (" and the README table" if BEGIN in readme else ""))


if __name__ == "__main__":
    main()
